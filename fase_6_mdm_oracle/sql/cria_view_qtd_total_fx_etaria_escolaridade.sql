-- Quantidade de cidadaos por faixa etaria e escolaridade.
-- Inclui registros com valores nulos e com divergencias.

CREATE OR REPLACE VIEW VW_MDM_FX_ETARIA_ESCOLARIDADE AS
SELECT
    NM_FAIXA_ETARIA,
    NM_ESCOLARIDADE,
    COUNT(*) AS QTDE_CIDADAOS
FROM T_MDM_CIDADAO
GROUP BY
    NM_FAIXA_ETARIA,
    NM_ESCOLARIDADE;


SELECT
    NVL(NM_FAIXA_ETARIA, 'SEM CLASSIFICACAO') AS FAIXA_ETARIA,
    NVL(NM_ESCOLARIDADE, 'NAO INFORMADA') AS ESCOLARIDADE,
    QTDE_CIDADAOS
FROM VW_MDM_FX_ETARIA_ESCOLARIDADE
ORDER BY
    CASE NM_FAIXA_ETARIA
        WHEN 'BEBE' THEN 1
        WHEN 'CRIANCA' THEN 2
        WHEN 'ADOLESCENTE' THEN 3
        WHEN 'ADULTO' THEN 4
        WHEN 'IDOSO' THEN 5
        ELSE 6
    END,
    NM_ESCOLARIDADE;


SELECT
    SUM(QTDE_CIDADAOS) AS TOTAL_CIDADAOS_NA_VIEW
FROM VW_MDM_FX_ETARIA_ESCOLARIDADE;