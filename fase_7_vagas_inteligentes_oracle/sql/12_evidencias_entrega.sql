-- RN04: eventos rejeitados por sensor/vaga nao cadastrado
SELECT *
FROM (
    SELECT
        e.ID_EVENTO_SENSOR,
        e.CD_SENSOR,
        e.NR_VAGA,
        e.FL_PROCESSADO,
        l.DS_MOTIVO_ERRO
    FROM T_STG_EVENTO_SENSOR_VAGA e
    JOIN T_LOG_ERRO_EVENTO l
      ON l.ID_EVENTO_SENSOR = e.ID_EVENTO_SENSOR
    WHERE l.DS_MOTIVO_ERRO =
          'Sensor/vaga nao localizado no cadastro.'
      AND e.FL_PROCESSADO = 'E'
    ORDER BY e.ID_EVENTO_SENSOR
)
WHERE ROWNUM <= 5;


-- RN05: cobranca gravada e comparacao com o valor esperado
SELECT *
FROM (
    SELECT
        p.ID_PERMANENCIA,
        v.TP_VAGA,
        p.NR_TEMPO_PERMANENCIA_MIN AS MINUTOS,
        par.NR_MINUTOS_TEMPO_LIVRE AS MINUTOS_LIVRES,
        par.VL_MINUTO_VAGA AS TARIFA,
        c.NR_MINUTOS_EXCEDENTES AS EXCEDENTES,
        c.VL_COBRANCA AS VALOR_GRAVADO,
        ROUND(
            (p.NR_TEMPO_PERMANENCIA_MIN
             - par.NR_MINUTOS_TEMPO_LIVRE)
            * par.VL_MINUTO_VAGA, 2
        ) AS VALOR_ESPERADO
    FROM T_PERMANENCIA_VEICULO p
    JOIN T_VAGA v
      ON v.CD_SENSOR = p.CD_SENSOR
     AND v.NR_VAGA = p.NR_VAGA
    JOIN T_COBRANCA_VAGA c
      ON c.ID_PERMANENCIA = p.ID_PERMANENCIA
    JOIN T_PARAMETROS_ESTACIONAMENTO par
      ON p.DT_ENTRADA >= par.DT_INICIO_VIGENCIA
     AND (
         par.DT_TERMINO_VIGENCIA IS NULL
         OR p.DT_ENTRADA <= par.DT_TERMINO_VIGENCIA
     )
    ORDER BY p.ID_PERMANENCIA
)
WHERE ROWNUM <= 5;


-- RN06: vagas especiais acima do limite gratuito
-- A contagem de cobrancas deve ser zero para os dois tipos.
SELECT
    v.TP_VAGA,
    par.NR_MINUTOS_TEMPO_LIVRE AS LIMITE_GRATUITO,
    COUNT(DISTINCT p.ID_PERMANENCIA) AS PERMANENCIAS,
    MIN(p.NR_TEMPO_PERMANENCIA_MIN) AS MENOR_TEMPO_MIN,
    MAX(p.NR_TEMPO_PERMANENCIA_MIN) AS MAIOR_TEMPO_MIN,
    COUNT(c.ID_COBRANCA) AS COBRANCAS_ASSOCIADAS
FROM T_PERMANENCIA_VEICULO p
JOIN T_VAGA v
  ON v.CD_SENSOR = p.CD_SENSOR
 AND v.NR_VAGA = p.NR_VAGA
JOIN T_PARAMETROS_ESTACIONAMENTO par
  ON p.DT_ENTRADA >= par.DT_INICIO_VIGENCIA
 AND (
     par.DT_TERMINO_VIGENCIA IS NULL
     OR p.DT_ENTRADA <= par.DT_TERMINO_VIGENCIA
 )
LEFT JOIN T_COBRANCA_VAGA c
  ON c.ID_PERMANENCIA = p.ID_PERMANENCIA
WHERE v.TP_VAGA IN ('IDOSO', 'PCD')
  AND p.NR_TEMPO_PERMANENCIA_MIN >
      par.NR_MINUTOS_TEMPO_LIVRE
GROUP BY v.TP_VAGA, par.NR_MINUTOS_TEMPO_LIVRE
ORDER BY v.TP_VAGA;


