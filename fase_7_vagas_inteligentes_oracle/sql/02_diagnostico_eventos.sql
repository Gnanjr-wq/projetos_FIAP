-- 1. Distribuicao dos eventos entre ocupacao e saida
SELECT ST_VAGA, COUNT(*) AS QUANTIDADE
FROM T_STG_EVENTO_SENSOR_VAGA
GROUP BY ST_VAGA
ORDER BY ST_VAGA;

-- 2. Distribuicao das vagas por tipo e situacao
SELECT TP_VAGA, FL_ATIVA, COUNT(*) AS QUANTIDADE
FROM T_VAGA
GROUP BY TP_VAGA, FL_ATIVA
ORDER BY TP_VAGA, FL_ATIVA;

-- 3. Eventos cujo sensor/vaga nao existe no cadastro
SELECT COUNT(*) AS EVENTOS_SEM_VAGA_CADASTRADA
FROM T_STG_EVENTO_SENSOR_VAGA e
WHERE NOT EXISTS (
    SELECT 1
    FROM T_VAGA v
    WHERE v.CD_SENSOR = e.CD_SENSOR
      AND v.NR_VAGA   = e.NR_VAGA
);

-- 4. Repeticoes de sensor, vaga e instante do evento
SELECT
    CD_SENSOR,
    NR_VAGA,
    TO_CHAR(DT_EVENTO, 'DD/MM/YYYY HH24:MI:SS') AS DATA_EVENTO,
    COUNT(*) AS QUANTIDADE
FROM T_STG_EVENTO_SENSOR_VAGA
GROUP BY CD_SENSOR, NR_VAGA, DT_EVENTO
HAVING COUNT(*) > 1
ORDER BY CD_SENSOR, NR_VAGA, DT_EVENTO;

-- 5. Quantificar grupos repetidos e registros excedentes
SELECT
    COUNT(*) AS GRUPOS_REPETIDOS,
    NVL(SUM(QUANTIDADE), 0) AS EVENTOS_NOS_GRUPOS,
    NVL(SUM(QUANTIDADE - 1), 0) AS EVENTOS_EXCEDENTES
FROM (
    SELECT COUNT(*) AS QUANTIDADE
    FROM T_STG_EVENTO_SENSOR_VAGA
    GROUP BY CD_SENSOR, NR_VAGA, DT_EVENTO
    HAVING COUNT(*) > 1
);

-- 6. Verificar se ha eventos associados a vagas inativas
SELECT COUNT(*) AS EVENTOS_EM_VAGAS_INATIVAS
FROM T_STG_EVENTO_SENSOR_VAGA e
JOIN T_VAGA v
  ON v.CD_SENSOR = e.CD_SENSOR
 AND v.NR_VAGA   = e.NR_VAGA
WHERE v.FL_ATIVA = 'N';