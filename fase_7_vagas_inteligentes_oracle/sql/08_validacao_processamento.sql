-- 1. Conferir os status dos eventos
SELECT FL_PROCESSADO, COUNT(*) AS QUANTIDADE
FROM T_STG_EVENTO_SENSOR_VAGA
GROUP BY FL_PROCESSADO
ORDER BY FL_PROCESSADO;

-- 2. Conferir os totais gravados
SELECT 'PERMANENCIAS' AS TABELA, COUNT(*) AS QUANTIDADE
FROM T_PERMANENCIA_VEICULO
UNION ALL
SELECT 'COBRANCAS', COUNT(*)
FROM T_COBRANCA_VAGA
UNION ALL
SELECT 'LOGS_DE_ERRO', COUNT(*)
FROM T_LOG_ERRO_EVENTO;

-- 3. Identificar os motivos das rejeicoes
SELECT DS_MOTIVO_ERRO, COUNT(*) AS QUANTIDADE
FROM T_LOG_ERRO_EVENTO
GROUP BY DS_MOTIVO_ERRO
ORDER BY QUANTIDADE DESC, DS_MOTIVO_ERRO;

-- 4. Classificar permanencias com e sem cobranca
WITH classificacao AS (
    SELECT
        CASE
            WHEN EXISTS (
                SELECT 1
                FROM T_COBRANCA_VAGA c
                WHERE c.ID_PERMANENCIA = p.ID_PERMANENCIA
            ) THEN 'COM COBRANCA'
            ELSE 'SEM COBRANCA'
        END AS SITUACAO,
        v.TP_VAGA
    FROM T_PERMANENCIA_VEICULO p
    JOIN T_VAGA v
      ON v.CD_SENSOR = p.CD_SENSOR
     AND v.NR_VAGA = p.NR_VAGA
)
SELECT SITUACAO, TP_VAGA, COUNT(*) AS QUANTIDADE
FROM classificacao
GROUP BY SITUACAO, TP_VAGA
ORDER BY SITUACAO, TP_VAGA;

-- 5. Verificar se alguma permanencia recebeu mais de uma cobranca
SELECT ID_PERMANENCIA, COUNT(*) AS QUANTIDADE
FROM T_COBRANCA_VAGA
GROUP BY ID_PERMANENCIA
HAVING COUNT(*) > 1;