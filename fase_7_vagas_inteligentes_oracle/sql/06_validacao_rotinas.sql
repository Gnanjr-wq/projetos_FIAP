-- Conferir as quatro rotinas preparadas
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
FROM USER_OBJECTS
WHERE OBJECT_NAME IN (
    'FUN_CALCULAR_TEMPO_PERMANENCIA',
    'FUN_MASCARAR_PLACA',
    'FUN_DEVE_COBRAR',
    'PRC_REGISTRAR_ERRO'
)
  AND OBJECT_TYPE IN ('FUNCTION', 'PROCEDURE')
ORDER BY OBJECT_TYPE, OBJECT_NAME;

-- Consultar erros de compilacao
SELECT NAME, TYPE, LINE, POSITION, TEXT
FROM USER_ERRORS
WHERE NAME IN (
    'FUN_CALCULAR_TEMPO_PERMANENCIA',
    'FUN_MASCARAR_PLACA',
    'FUN_DEVE_COBRAR',
    'PRC_REGISTRAR_ERRO'
)
ORDER BY NAME, SEQUENCE;

