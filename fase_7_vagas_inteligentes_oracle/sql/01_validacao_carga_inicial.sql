-- Quantidade de registros em cada tabela
SELECT 'T_VAGA' AS tabela, COUNT(*) AS quantidade
FROM T_VAGA
UNION ALL
SELECT 'T_STG_EVENTO_SENSOR_VAGA', COUNT(*)
FROM T_STG_EVENTO_SENSOR_VAGA
UNION ALL
SELECT 'T_PARAMETROS_ESTACIONAMENTO', COUNT(*)
FROM T_PARAMETROS_ESTACIONAMENTO
UNION ALL
SELECT 'T_PERMANENCIA_VEICULO', COUNT(*)
FROM T_PERMANENCIA_VEICULO
UNION ALL
SELECT 'T_COBRANCA_VAGA', COUNT(*)
FROM T_COBRANCA_VAGA
UNION ALL
SELECT 'T_LOG_ERRO_EVENTO', COUNT(*)
FROM T_LOG_ERRO_EVENTO;

-- Status inicial dos eventos
SELECT
    FL_PROCESSADO,
    COUNT(*) AS quantidade
FROM T_STG_EVENTO_SENSOR_VAGA
GROUP BY FL_PROCESSADO;

-- Parametros de cobranca
SELECT
    NR_MINUTOS_TEMPO_LIVRE,
    VL_MINUTO_VAGA,
    TO_CHAR(DT_INICIO_VIGENCIA, 'DD/MM/YYYY') AS inicio_vigencia,
    TO_CHAR(DT_TERMINO_VIGENCIA, 'DD/MM/YYYY') AS termino_vigencia
FROM T_PARAMETROS_ESTACIONAMENTO;