WITH revisao AS (
    SELECT
        p.ID_PERMANENCIA,
        v.TP_VAGA,
        p.NR_TEMPO_PERMANENCIA_MIN AS MIN_ATUAIS,
        ROUND(
            ROUND((p.DT_SAIDA - p.DT_ENTRADA) * 86400) / 60
        ) AS MIN_CORRETOS
    FROM T_PERMANENCIA_VEICULO p
    JOIN T_VAGA v
      ON v.CD_SENSOR = p.CD_SENSOR
     AND v.NR_VAGA = p.NR_VAGA
)
SELECT
    r.ID_PERMANENCIA,
    r.TP_VAGA,
    r.MIN_ATUAIS,
    r.MIN_CORRETOS,
    c.ID_COBRANCA,
    c.VL_COBRANCA AS VALOR_ATUAL,
    CASE
        WHEN r.TP_VAGA = 'COMUM' AND r.MIN_CORRETOS > 30
        THEN ROUND((r.MIN_CORRETOS - 30) * 0.20, 2)
        ELSE 0
    END AS VALOR_ESPERADO
FROM revisao r
LEFT JOIN T_COBRANCA_VAGA c
  ON c.ID_PERMANENCIA = r.ID_PERMANENCIA
WHERE r.MIN_ATUAIS IS NULL
   OR r.MIN_ATUAIS <> r.MIN_CORRETOS
ORDER BY r.ID_PERMANENCIA;